/**
 * Copy the canonical sources in plugins/shared/ to each plugin.
 *
 * At install time each client copies and reads only its own plugin directory, so it cannot reference
 * plugins/shared/ which lives outside the plugin. We therefore keep a single canonical source and place
 * copies at each destination. We do not use symlinks because we have not verified whether Antigravity and
 * Kiro follow symlinks at install time.
 *
 * The list of distributed copies is recorded in plugins/.sync-manifest, so that when an entry is removed
 * from COPIES or renamed, the previously distributed leftover can be removed (a leftover is
 * indistinguishable from a copy if you forget to delete it by hand).
 *
 * Usage: npm run sync:plugins (copy) / npm run sync:plugins -- --check (list out-of-sync copies and fail).
 * test/plugins.test.ts runs the same checks as --check.
 */
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const MANIFEST = 'plugins/.sync-manifest';

const SKILL = 'skills/lockage-workflow/SKILL.md';

export interface Copy {
  from: string;
  to: string;
}

const same = (file: string, dirs: string[]): Copy[] =>
  dirs.map((dir) => ({ from: join('plugins/shared', file), to: join(dir, file) }));

export const COPIES: Copy[] = [
  // Kiro copies only POWER.md, mcp.json, and steering/ at install time, so place it under steering/
  ...same('AGENTS.md', ['plugins/claude', 'plugins/antigravity']),
  { from: 'plugins/shared/AGENTS.md', to: 'plugins/kiro/steering/AGENTS.md' },
  ...same(SKILL, ['plugins/claude', 'plugins/antigravity']),
  { from: join('plugins/shared', SKILL), to: 'plugins/kiro/steering/lockage-workflow.md' },
];

export function copies(): Copy[] {
  return COPIES;
}

function readManifest(root: string): string[] {
  const path = join(root, MANIFEST);
  if (!existsSync(path)) return [];
  return (
    readFileSync(path, 'utf8')
      // A checkout with core.autocrlf produces CRLF
      .split(/\r?\n/)
      .filter((line) => line && !line.startsWith('#'))
      // Only destinations (under plugins/) may be deleted. Do not delete outside the repo via a hand-edited line
      .filter((line) => /^plugins\//.test(line) && !line.split('/').includes('..'))
  );
}

function manifestText(): string {
  const lines = COPIES.map(({ to }) => to).sort();
  return `# Generated by \`npm run sync:plugins\`. Do not edit by hand.\n${lines.join('\n')}\n`;
}

/** Return copies whose contents or execute permission differ from the canonical source (including missing ones). */
export function outOfSync(root = ROOT): Copy[] {
  return COPIES.filter(({ from, to }) => {
    const src = join(root, from);
    const dst = join(root, to);
    if (!existsSync(dst)) return true;
    if (!readFileSync(src).equals(readFileSync(dst))) return true;
    return (statSync(src).mode & 0o111) !== (statSync(dst).mode & 0o111);
  });
}

/** Return files that were distributed previously but remain even though they are no longer in COPIES. */
export function leftovers(root = ROOT): string[] {
  const current = new Set(COPIES.map(({ to }) => to));
  return readManifest(root).filter((to) => !current.has(to) && existsSync(join(root, to)));
}

/** Whether the manifest disagrees with COPIES (i.e. sync was not run). */
export function manifestStale(root = ROOT): boolean {
  const path = join(root, MANIFEST);
  return !existsSync(path) || readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== manifestText();
}

export function sync(root = ROOT): string[] {
  const changed: string[] = [];
  for (const to of leftovers(root)) {
    rmSync(join(root, to));
    changed.push(`deleted: ${to}`);
  }
  for (const { from, to } of outOfSync(root)) {
    const dst = join(root, to);
    mkdirSync(dirname(dst), { recursive: true });
    copyFileSync(join(root, from), dst);
    chmodSync(dst, statSync(join(root, from)).mode & 0o777);
    changed.push(`updated: ${to}`);
  }
  if (manifestStale(root)) {
    writeFileSync(join(root, MANIFEST), manifestText());
    changed.push(`updated: ${MANIFEST}`);
  }
  return changed;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const problems = [
      ...outOfSync().map(({ from, to }) => `${to} is out of sync with ${from}`),
      ...leftovers().map((to) => `${to} remains even though it is no longer distributed`),
      ...(manifestStale() ? [`${MANIFEST} disagrees with the list of distributed copies`] : []),
    ];
    for (const p of problems) console.error(p);
    if (problems.length > 0) {
      console.error('Run `npm run sync:plugins` to reconcile (fix the canonical source in plugins/shared/, not the copies)');
      process.exit(1);
    }
  } else {
    for (const line of sync()) console.log(line);
  }
}
